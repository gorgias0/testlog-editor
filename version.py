import functools
import os
import subprocess
import sys
from datetime import date


VERSION_PREFIX = "1.0"
UNKNOWN = "unknown"
BUILD_INFO_MODULE = "_build_info"


def format_version(commit_count, dirty=False):
    # One patch number per commit on main, so every pushed change gets a new version.
    if commit_count is None:
        return UNKNOWN
    return f"{VERSION_PREFIX}.{commit_count}" + ("+dirty" if dirty else "")


def _git(repo_dir, *args):
    try:
        result = subprocess.run(
            ["git", "-C", str(repo_dir), *args],
            capture_output=True,
            text=True,
            timeout=5,
            # Avoid a console window flashing up when started with pythonw on Windows.
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
        )
    except (OSError, subprocess.SubprocessError):
        return None
    if result.returncode != 0:
        return None
    return result.stdout.strip()


def collect_build_info(repo_dir):
    count = _git(repo_dir, "rev-list", "--count", "HEAD")
    commit = _git(repo_dir, "rev-parse", "--short", "HEAD")
    # Untracked files (local scripts, build output) do not make a build dirty; edits to tracked files do.
    status = _git(repo_dir, "status", "--porcelain", "--untracked-files=no")
    return {
        "version": format_version(int(count) if count and count.isdigit() else None, bool(status)),
        "commit": commit or UNKNOWN,
        "build_date": date.today().isoformat(),
    }


def write_build_info(path, info):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("# Generated by testlog.spec at build time. Do not edit or commit.\n")
        f.write(f"BUILD_INFO = {info!r}\n")


@functools.lru_cache(maxsize=1)
def get_version_info():
    # A packaged app has no git checkout, so it uses the info written at build time.
    # From source, ask git directly; a _build_info.py left over from a build would be stale.
    if getattr(sys, "frozen", False):
        try:
            from _build_info import BUILD_INFO
        except ImportError:
            return {"version": UNKNOWN, "commit": UNKNOWN, "build_date": UNKNOWN}
        return BUILD_INFO
    info = collect_build_info(os.path.dirname(os.path.abspath(__file__)))
    info["build_date"] = None
    return info
